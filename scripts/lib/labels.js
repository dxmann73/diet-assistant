const LANGUAGES = Object.keys(LABELS);

function labelsFor(language) {
  const L = LABELS[language];
  if (!L) {
    throw new Error(
      `unknown language ${JSON.stringify(language)}, expected one of ${LANGUAGES.join('|')}`
    );
  }
  return L;
}

module.exports = { LABELS, LANGUAGES, labelsFor };
